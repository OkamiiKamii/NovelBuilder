// Builds the reader's page (reader-web/) into one HTML string the app carries: src/reader/readerPage.generated.ts.
// Run after changing anything in reader-web/:   npm run build:pages
//
// The page loads nothing from a network. The book's typefaces are the device's own (as the Flutter reader uses them),
// plus the app's fonts from the Android app's resources (file:///android_res/font/, where expo-font's families put them).

import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

const result = await build({
  entryPoints: [join(root, 'reader-web', 'main.ts')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: 'es2020',
  write: false,
  legalComments: 'none',
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

// The look (typeface, size, colours, spacing) comes from the app as the dynamic style; these are the fixed parts.
const css = `
@font-face { font-family: 'Merriweather'; font-weight: 300 900; src: url('file:///android_res/font/merriweather.ttf'); }
@font-face { font-family: 'Merriweather'; font-style: italic; font-weight: 300 900; src: url('file:///android_res/font/merriweather_italic.ttf'); }
@font-face { font-family: 'Outfit'; font-weight: 100 900; src: url('file:///android_res/font/outfit.ttf'); }
:root { --bg: #FFFFFF; --fg: #1A1A1A; --muted: rgba(26,26,26,0.65); --size: 18px; --leading: 1.5; --measure: 34em;
  --font: serif; --align: left; --pad: 20px; }
html, body { margin: 0; padding: 0; background: var(--bg); color: var(--fg); -webkit-text-size-adjust: 100%; }
body { font-family: var(--font); font-size: var(--size); line-height: var(--leading); }
#book.paged { height: 100vh; overflow: hidden; }
#book.paged .columns {
  height: 100vh; box-sizing: border-box; padding: var(--pad) 0; column-width: 100vw; column-gap: 0; column-fill: auto;
  transition: transform 0.25s ease;
}
@media (prefers-reduced-motion: reduce) { #book.paged .columns { transition: none; } }
#book.paged .columns > * { box-sizing: border-box; padding-left: max(var(--pad), calc((100vw - var(--measure)) / 2));
  padding-right: max(var(--pad), calc((100vw - var(--measure)) / 2)); }
#book.scroll, #book.serial { padding: var(--pad) 0 40vh; }
#book.scroll .section > *, #book.serial > * { max-width: var(--measure); margin-left: auto; margin-right: auto;
  padding-left: var(--pad); padding-right: var(--pad); box-sizing: content-box; }
#book.scroll .section { padding-bottom: 3em; }
p { margin: 0; text-align: var(--align); orphans: 2; widows: 2; }
.label { text-align: center; font-size: 0.8em; letter-spacing: 0.15em; color: var(--muted); break-after: avoid; }
.heading { text-align: center; font-size: 1.5em; line-height: 1.25; font-weight: 600; break-after: avoid; margin: 0; }
.subheading { font-weight: 600; break-after: avoid; margin: 1em 0 0.5em; }
.matter { text-align: center; text-indent: 0; }
.break { text-align: center; margin: 0.5em 0; }
.list { padding-left: 1.5em !important; text-indent: -0.9em; }
.cover { height: calc(100vh - 2 * var(--pad)); display: flex; flex-direction: column; align-items: center;
  justify-content: center; text-align: center; padding: 24px; box-sizing: border-box; }
.cover img { max-width: 100%; max-height: 100%; object-fit: contain; }
.contents a { display: block; color: var(--fg); text-decoration: none; padding: 0.35em 0; }
.contents a.here { font-weight: 700; }
.note { margin: 0.75em 0; padding: 8px 8px 8px 16px; border-left: 3px solid var(--muted); font-style: italic; color: var(--muted); }
.nav { display: flex; flex-wrap: wrap; justify-content: space-between; gap: 8px; margin: 1em 0; }
.nav a { color: var(--fg); border: 1px solid var(--muted); border-radius: 20px; padding: 8px 14px; text-decoration: none;
  font-family: 'Outfit', sans-serif; font-size: 0.8em; max-width: 45%; overflow: hidden; text-overflow: ellipsis; white-space: nowrap; }
.nav a.off { opacity: 0.35; pointer-events: none; }
`;

const html = `<!DOCTYPE html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no">
<style>${css}</style><style id="dynamic-style"></style></head>
<body><main id="book"></main><script>${script}</script></body></html>`;

mkdirSync(join(root, 'src', 'reader'), { recursive: true });
const out = `// GENERATED by tool/build-reader.mjs from reader-web/: do not edit. Rebuild with \`npm run build:pages\`.
// The reader's page, ${Math.round(html.length / 1024)} KB.
export const readerPageHtml: string = ${JSON.stringify(html)};
`;
writeFileSync(join(root, 'src', 'reader', 'readerPage.generated.ts'), out);
console.log(`Built src/reader/readerPage.generated.ts (${Math.round(html.length / 1024)} KB)`);
