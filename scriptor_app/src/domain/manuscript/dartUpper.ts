function unchangedInDart(c: number): boolean {
  for (let i = 0; i < dartUnchanged.length; i += 2) {
    if (c < dartUnchanged[i]) return false;
    if (c <= dartUnchanged[i + 1]) return true;
  }
  return false;
}

/** One UTF-16 unit ([unit] is a string of length one) in upper case, as Dart's `unit.toUpperCase()` on the Dart VM. */
export function dartUpperUnit(unit: string): string {
  const c = unit.charCodeAt(0);
  if (c < 0x80) return unit.toUpperCase();
  // Greek with a ypogegrammeni: Dart's simple mapping to the capital with a prosgegrammeni.
  if ((c >= 0x1f80 && c <= 0x1f87) || (c >= 0x1f90 && c <= 0x1f97) || (c >= 0x1fa0 && c <= 0x1fa7)) {
    return String.fromCharCode(c + 8);
  }
  if (c === 0x1fb3 || c === 0x1fc3 || c === 0x1ff3) return String.fromCharCode(c + 9);
  return unchangedInDart(c) ? unit : unit.toUpperCase();
}
